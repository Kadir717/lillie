/**
 * LILLIE — Portfolio Export
 *
 * Deterministic export builders for the generated portfolio:
 *   - `json`     → the full PortfolioContent payload (machine-readable)
 *   - `html`     → a self-contained personal-website page with the theme
 *     applied inline (zero external assets — works offline, paste anywhere)
 *   - `markdown` → a README-style portfolio document
 *
 * All three consume the SAME PortfolioContent — no re-implementation of
 * the generators, no duplicated data shapes. HTML is built with a small
 * escaper so GitHub-supplied text (bio, descriptions) can never inject
 * markup into the generated site.
 */

import type { PortfolioContent } from "./types";
import type { PortfolioTheme } from "./themes";

// ═══════════════════════════════════════════════════════════════════
// Escaping
// ═══════════════════════════════════════════════════════════════════

/** Escapes text for safe inclusion in generated HTML. */
function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

/**
 * URL scheme whitelist — the same rule as src/lib/sanitize-model.ts.
 * escapeHtml escapes markup but does NOT stop `javascript:` URLs in
 * href/src attributes, so URLs must be http(s) only.
 */
const SAFE_URL_RE = /^https?:\/\//i;

function safeUrl(value: string): string {
  const trimmed = value.trim();
  return SAFE_URL_RE.test(trimmed) ? trimmed : "";
}

