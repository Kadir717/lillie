export function buildPortfolioMarkdown(content: PortfolioContent): string {
  const { hero, stats, about, skills, featuredProjects, achievements, techStack } = content;
  const lines: string[] = [];

  lines.push(`# ${hero.name}`);
  lines.push("");
  if (hero.headline) lines.push(`> ${hero.headline}`);
  if (hero.bio) lines.push("");
  if (hero.bio) lines.push(hero.bio);
  lines.push("");
  lines.push(`- **Repositories:** ${stats.repos}`);
  lines.push(`- **Stars:** ${stats.stars}`);
  lines.push(`- **Forks:** ${stats.forks}`);
  lines.push(`- **Years on GitHub:** ${stats.years}`);
  if (hero.location) lines.push(`- **Location:** ${hero.location}`);
  if (hero.website) lines.push(`- **Website:** ${hero.website}`);
  lines.push("");

  lines.push("## About");
  lines.push("");
  about.paragraphs.forEach((p) => lines.push(p, ""));
  if (about.highlights.length > 0) {
    lines.push("**Highlights:** " + about.highlights.join(", "));
    lines.push("");
  }

  if (skills.length > 0) {
    lines.push("## Skills");
    lines.push("");
    lines.push(skills.map((s) => s.name).join(", "));
    lines.push("");
  }

  if (featuredProjects.length > 0) {
    lines.push("## Featured Projects");
    lines.push("");
    for (const p of featuredProjects) {
      lines.push(`### ${p.name}`);
      lines.push("");
      lines.push(p.description || "No description yet.");
      lines.push("");
      lines.push(
        `- ${p.stars} stars · ${p.forks} forks` +
          (p.language ? ` · ${p.language}` : "") +
          (p.topics.length > 0 ? ` · ${p.topics.slice(0, 4).join(", ")}` : "")
      );
      lines.push("");
      lines.push(p.url);
      lines.push("");
    }
  }

  const earned = achievements.filter((a) => a.earned);
  if (earned.length > 0) {
    lines.push("## Achievements");
    lines.push("");
    earned.forEach((a) => lines.push(`- ${a.icon} **${a.title}** — ${a.description}`));
    lines.push("");
  }

  if (techStack.length > 0) {
    lines.push("## Tech Stack");
    lines.push("");
    lines.push(
      techStack
        .map((t) => `${t.name} (${t.percent}%)`)
        .join(" · ")
    );
    lines.push("");
  }

  lines.push(`---`);
  lines.push(`_Generated by LILLIE — theme: ${content.themeId}_`);
  lines.push("");
  return lines.join("\n");
}

